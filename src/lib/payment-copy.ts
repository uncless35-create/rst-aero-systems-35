/**
 * Как оплачивается заказ, пока онлайн-оплата не подключена: при получении.
 * СДЭК везёт наложенным платежом и сам принимает деньги в пункте выдачи или у курьера.
 */
export function payOnDeliveryText(deliveryProvider: string | null | undefined): string {
  return deliveryProvider === "CDEK"
    ? "Оплата при получении — наличными или картой в пункте выдачи СДЭК или курьеру (наложенный платёж). Предоплата не нужна."
    : "Оплата при самовывозе — на месте, наличными или переводом.";
}
